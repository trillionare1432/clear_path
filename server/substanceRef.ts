export interface SubstanceMatchResult {
  catalogueVersion: string;
  matchedEntry: ClinicalSubstanceRefEntry | null;
  confidence: 'high' | 'possible' | 'none';
  proposedStatus: 'catalogue' | 'unverified';
  explanation: string;
}

export function matchCustomSubstanceDescription(rawText: string): SubstanceMatchResult {
  const normalized = rawText.trim().toLowerCase();
  if (!normalized || normalized.length < 2) {
    return {
      catalogueVersion: CLINICAL_SUBSTANCE_CATALOGUE_VERSION,
      matchedEntry: null,
      confidence: 'none',
      proposedStatus: 'unverified',
      explanation: 'Description saved verbatim as Unverified for optional professional review.',
    };
  }

  for (const entry of CLINICAL_SUBSTANCE_ENTRIES) {
    if (entry.name.toLowerCase() === normalized) {
      return {
        catalogueVersion: CLINICAL_SUBSTANCE_CATALOGUE_VERSION,
        matchedEntry: entry,
        confidence: 'high',
        proposedStatus: 'catalogue',
        explanation: `Matched directly against ${CLINICAL_SUBSTANCE_CATALOGUE_VERSION}. Please confirm if this matches what you meant.`,
      };
    }
    for (const syn of entry.synonyms) {
      if (normalized === syn || (syn.length >= 4 && normalized.includes(syn))) {
        return {
          catalogueVersion: CLINICAL_SUBSTANCE_CATALOGUE_VERSION,
          matchedEntry: entry,
          confidence: normalized === syn ? 'high' : 'possible',
          proposedStatus: 'catalogue',
          explanation: `Recognized reference synonym "${syn}" in ${CLINICAL_SUBSTANCE_CATALOGUE_VERSION}. Please confirm if "${entry.name}" matches your situation.`,
        };
      }
    }
  }

  return {
    catalogueVersion: CLINICAL_SUBSTANCE_CATALOGUE_VERSION,
    matchedEntry: null,
    confidence: 'none',
    proposedStatus: 'unverified',
    explanation:
      'No verified catalogue match found. Your exact description has been preserved as "Unverified" so a qualified clinician can review it with you without guessing.',
  };
}
